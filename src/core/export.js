import { stringifyCSV } from "./csv.js";

export function downloadText(filename, type, text) {
  downloadBlob(filename, new Blob([text], { type }));
}

export function downloadBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function exportDatasetCSV(dataset) {
  if (!dataset?.rows?.length) throw new Error("There is no dataset to export.");
  downloadText(fileName(dataset.name) + ".csv", "text/csv;charset=utf-8", stringifyCSV(dataset.rows));
}

export function exportWorkspaceJSON(workspace) {
  downloadText("veya-workspace-backup.json", "application/json;charset=utf-8", JSON.stringify(workspace, null, 2));
}

export function exportChartPNG(svg) {
  return new Promise((resolve, reject) => {
    const copy = svg.cloneNode(true);
    copy.setAttribute("xmlns", "http://www.w3.org/2000/svg");
    copy.setAttribute("width", "1400");
    copy.setAttribute("height", "500");
    const serialized = new XMLSerializer().serializeToString(copy);
    const url = URL.createObjectURL(new Blob([serialized], { type: "image/svg+xml;charset=utf-8" }));
    const image = new Image();
    image.onload = () => {
      const canvas = document.createElement("canvas");
      canvas.width = 1400;
      canvas.height = 500;
      const context = canvas.getContext("2d");
      context.fillStyle = getComputedStyle(document.body).getPropertyValue("--panel") || "#fff";
      context.fillRect(0, 0, canvas.width, canvas.height);
      context.drawImage(image, 0, 0, canvas.width, canvas.height);
      URL.revokeObjectURL(url);
      canvas.toBlob(blob => blob ? (downloadBlob("veya-chart.png", blob), resolve()) : reject(new Error("Could not encode chart.")), "image/png");
    };
    image.onerror = () => { URL.revokeObjectURL(url); reject(new Error("Could not render chart image.")); };
    image.src = url;
  });
}

export function reportHTML(workspace, profile) {
  const dataset = workspace.datasets?.find(item => item.id === workspace.activeDatasetId);
  const title = dataset?.name || "Veya analysis";
  const columns = profile?.columns || [];
  const findings = profile?.findings || [];
  const rows = dataset?.rows || [];
  return "<!doctype html><html><head><meta charset=\"utf-8\"><title>" + escapeHTML(title) + " — Veya report</title><style>" +
    "body{font:15px/1.6 system-ui,sans-serif;max-width:900px;margin:48px auto;padding:0 24px;color:#252431}h1,h2{font-family:system-ui,sans-serif;letter-spacing:-.03em}h1{font-size:34px}h2{margin-top:34px;font-size:20px}small{color:#777}table{width:100%;border-collapse:collapse}td,th{text-align:left;padding:9px;border-bottom:1px solid #ddd;font-size:13px}.finding{padding:12px 0;border-bottom:1px solid #eee}.meta{color:#666}</style></head><body><small>VEYA DATA STUDIO · ANALYSIS REPORT</small><h1>" + escapeHTML(title) + "</h1><p class=\"meta\">" + rows.length + " rows · " + (profile?.columnCount || 0) + " columns · Quality score " + (profile?.qualityScore ?? "—") + "/100</p><h2>Dataset profile</h2><table><thead><tr><th>Column</th><th>Type</th><th>Values</th><th>Missing</th><th>Unique</th></tr></thead><tbody>" +
    columns.map(column => "<tr><td>" + escapeHTML(column.name) + "</td><td>" + escapeHTML(column.type) + "</td><td>" + column.count + "</td><td>" + column.missingCount + "</td><td>" + column.uniqueCount + "</td></tr>").join("") +
    "</tbody></table><h2>Things worth investigating</h2>" + findings.map(item => "<div class=\"finding\"><strong>" + escapeHTML(item.title) + "</strong><p>" + escapeHTML(item.detail) + "</p><small>" + escapeHTML(item.evidence) + "</small></div>").join("") +
    "<h2>Method and limitations</h2><p>Numeric summaries and quality flags were calculated from rows in this workspace. Outliers use the 1.5×IQR rule. Correlation does not establish causation. Forecasts, if included, use a simple moving average and are not guaranteed outcomes.</p><p>Generated by Veya · " + new Date().toLocaleString() + "</p></body></html>";
}

export function downloadReport(workspace, profile) {
  downloadText("veya-analysis-report.html", "text/html;charset=utf-8", reportHTML(workspace, profile));
}

export function printReport(workspace, profile) {
  const popup = window.open("", "_blank");
  if (!popup) throw new Error("The browser blocked the report window. Allow pop-ups for this local app, then try again.");
  popup.opener = null;
  popup.document.open();
  popup.document.write(reportHTML(workspace, profile));
  popup.document.close();
  popup.focus();
  setTimeout(() => popup.print(), 350);
}

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&#39;"
  })[character]);
}
function fileName(value) {
  return String(value || "dataset").normalize("NFKD").replace(/[^a-z0-9_-]+/gi, "-").replace(/^-+|-+$/g, "").toLowerCase() || "dataset";
}